require('reflect-metadata');
const assert=require('node:assert/strict');
const {test}=require('node:test');
const {randomUUID}=require('node:crypto');
const {Pool}=require('pg');
const {migrate}=require('../../scripts/database.cjs');
const {AmenitiesService}=require('../../dist/modules/beaches/amenities.service');
const {BeachesService}=require('../../dist/modules/beaches/beaches.service');

test('amenities: persistence, radius, same-name parking, freshness and catalogue consistency',async t=>{
  const url=new URL(process.env.TEST_DATABASE_URL);assert.equal(url.pathname,'/littora_ci_test');
  const admin=new Pool({connectionString:url.href});const name='littora_ci_poi_'+randomUUID().replaceAll('-','');
  await admin.query(`create database "${name}" template template0`);url.pathname='/'+name;
  const pool=new Pool({connectionString:url.href});
  t.after(async()=>{await pool.end();try{await admin.query(`drop database "${name}"`);}finally{await admin.end();}});
  await migrate(pool);
  const beach={id:randomUUID(),lat:43,lon:6};
  await pool.query("insert into beaches(id,name,lat,lon,has_parking,has_lifeguard) values($1,'Test',43,6,true,true)",[beach.id]);
  const service=new AmenitiesService(pool);const catalogue=new BeachesService(pool,{},service);
  const original=(await pool.query('select to_jsonb(b) as row from beaches b')).rows;
  assert.equal((await catalogue.get(beach.id)).has_parking,null);
  const points=Array.from({length:8},(_,i)=>({id:'node/'+(i+1),name:'Parking',category:'parking',lat:43+i*.0001,lon:6}));
  points.push({id:'node/20',name:'Far',category:'parking',lat:43.035,lon:6});
  points.push({id:'node/21',name:'Station',category:'rescue',lat:43,lon:6});
  await service.persist(beach,points,'https://overpass-api.de/api/interpreter');
  await service.persist(beach,points,'https://overpass-api.de/api/interpreter');
  let result=await service.get(beach.id);
  assert.equal(result.amenities.length,9);assert.equal(result.total,9);
  assert.ok(result.amenities.every(p=>p.distanceKm<=2.5&&p.inService===null));
  const detail=await catalogue.get(beach.id);
  assert.equal(detail.has_parking,true);assert.equal(detail.has_toilets,null);assert.equal(detail.has_lifeguard,null);
  assert.equal(detail.facilities.rescueStation.value,true);
  assert.deepEqual(detail.facilities,(await catalogue.catalogue()).beaches[0].facilities);
  assert.deepEqual((await pool.query('select to_jsonb(b) as row from beaches b')).rows,original);
  await pool.query("update beach_amenity_collections set fetched_at=now()-interval '12 hours',attempted_at=now(),error_code='unavailable'");
  result=await service.get(beach.id);assert.equal(result.status,'stale');assert.equal(result.total,9);
  await pool.query("update beach_amenity_collections set fetched_at=now()-interval '8 days'");
  assert.equal((await service.get(beach.id)).status,'unknown');assert.equal((await catalogue.get(beach.id)).has_parking,null);
  await service.persist(beach,[],'https://overpass-api.de/api/interpreter');
  assert.equal((await service.get(beach.id)).total,0);assert.equal((await catalogue.get(beach.id)).has_parking,null);
  await service.persist(beach,points,'https://overpass-api.de/api/interpreter');
  await pool.query('update beaches set lat=44 where id=$1',[beach.id]);
  assert.equal((await service.read(beach.id)).total,0);assert.equal((await catalogue.get(beach.id)).has_parking,null);
  await assert.rejects(service.persist(beach,[],'https://overpass-api.de/api/interpreter'),/position changed/);
  assert.equal((await pool.query('select count(*)::int n from beaches')).rows[0].n,1);
});
