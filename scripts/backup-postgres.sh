#!/usr/bin/env bash
set -euo pipefail
umask 077
export LC_ALL=C
fail() { printf '%s\n' "$1" >&2; exit 1; }

[[ ${BACKUP_DIR:-} == /* && -d $BACKUP_DIR && ! -L $BACKUP_DIR ]] || fail 'Set a private absolute BACKUP_DIR.'
dir=$(cd "$BACKUP_DIR" && pwd -P)
root=$(cd "$(dirname "$0")/.." && pwd -P)
[[ $dir != / && $dir != "$root" && $dir != "$root/"* ]] || fail 'Backups must be outside the repository.'
[[ -n $(find "$dir" -prune -user "$(id -un)" -perm 0700 -print) ]] || fail 'BACKUP_DIR must be owned by this account with mode 0700.'
[[ ${AGE_RECIPIENT:-} =~ ^age1[0-9a-z]+$ ]] || fail 'Set an age public recipient.'
days=${BACKUP_RETENTION_DAYS:-14}
[[ $days =~ ^([2-9]|[1-8][0-9]|90)$ ]] || fail 'Retention must be 2 to 90 days.'
container=${POSTGRES_CONTAINER:-}
if [[ -z $container ]]; then
  container=$(docker ps -q --filter label=com.docker.compose.project=littora-prod --filter label=com.docker.compose.service=postgres)
fi
[[ $container =~ ^[a-zA-Z0-9][a-zA-Z0-9_.-]*$ ]] || fail 'Expected one running PostgreSQL container.'
part=$(mktemp "$dir/.littora-pg.XXXXXXXX")
trap 'rm -f "$part"' EXIT
trap 'exit 1' HUP INT TERM
# pipefail also rejects an otherwise valid encryption of an incomplete pg_dump.
if ! { docker exec "$container" sh -eu -c 'exec pg_dump --no-password --format=custom -U "${POSTGRES_USER:?}" --dbname="${POSTGRES_DB:?}"' |
  age --encrypt -r "$AGE_RECIPIENT" > "$part"; } 2>/dev/null; then
  fail 'PostgreSQL backup failed; no archive published or expired.'
fi
archive="$dir/littora-pg-$(date -u +%Y%m%dT%H%M%SZ)-${part##*.}.dump.age"
ln "$part" "$archive" || fail 'Cannot publish archive atomically.'

# Retention applies only to regular files with names generated by this program.
for file in "$dir"/littora-pg-*.dump.age; do
  [[ -f $file && ! -L $file && $file != "$archive" ]] || continue
  [[ ${file##*/} =~ ^littora-pg-[0-9]{8}T[0-9]{6}Z-[a-zA-Z0-9]{8}\.dump\.age$ ]] || continue
  find "$file" -mtime "+$((days - 1))" -delete
done
printf '%s\n' "${archive##*/}"
